"""Runs the API with a STAND-IN for the language model, so the WebSocket chat can be tried (and its streaming, interrupt and reconnection seen) without model credentials.

    python scripts/chat_demo_server.py            # http://localhost:8000, in-memory checkpoints, a SQLite file under services/data/
    npm --prefix uis/backoffice run dev            # the backoffice on http://localhost:3001, "Ask TrackFlow"

Only the model's token stream and the vector search are replaced: the agent graph, its guardrails, the chat service, the WebSocket, the pub/sub and the database are the real ones. The stand-in
"model" answers slowly (a few tokens per second) so there is time to interrupt it, and it echoes the question it was given, so a redirected reply visibly reflects the new input.
Development only: the answers are not generated by a model. With LLM_API_URL / LLM_API_KEY / LLM_MODEL (and Qdrant) configured the real agent works the same way without this script.
"""

from __future__ import annotations

import os
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
(ROOT / "services" / "data").mkdir(parents=True, exist_ok=True)
os.environ.setdefault("DATABASE_URL", f"sqlite:///{(ROOT / 'services' / 'data' / 'chat-demo.db').as_posix()}")
os.environ.setdefault("JWT_SECRET", "chat-demo-only-secret-with-at-least-32-characters")
os.environ.setdefault("AUTH_DB_PATH", str(ROOT / "services" / "data" / "chat-demo-users.json"))
os.environ.setdefault("LLM_MODEL", "stand-in-model")
os.environ.setdefault("RFP_CHECKPOINT_DB", ":memory:")
os.environ.setdefault("RFP_AUTO_DRAFT", "false")

TOKEN_DELAY = float(os.getenv("CHAT_DEMO_TOKEN_DELAY", "0.07"))


def stand_in_answer(question: str) -> str:
    q = question.lower()
    if "return" in q or "refund" in q:
        body = ("I can help with your return. The standard return window is 30 days from delivery. To start it, tell me the order number and the reason, and I will generate the return label "
                "for you. The product is then inspected at the warehouse and classified as fit for resale, fit for reconditioning, or not fit. Return shipping is paid by the client brand unless "
                "the reason is a TrackFlow error.")
    elif "carrier" in q or "coverage" in q:
        body = ("TrackFlow works with UPS, FedEx and DHL in the United States and with MRW, SEUR and DHL in Spain. The system picks the carrier of each shipment by destination, weight, product type "
                "and urgency, so you do not need to choose one. If a destination needs special coverage, tell me where it is and I will check it with you.")
    else:
        body = ("Let me check your tracking information. I look up the order with its tracking number and read the latest status from the carrier. Standard shipping takes three to five business days "
                "within the same country, and express shipping takes 24 to 48 hours in the Los Angeles metropolitan area and the Zaragoza-Madrid corridor. Tell me the tracking number and I will tell you where it is.")
    return f"You asked: {question.strip()} {body}"


def main() -> None:
    from data.pipelines import rag
    from data.process import model_client

    def fake_stream(payload, on_open=None):
        question = re.search(r"Question: (.*)$", payload["messages"][-1]["content"], re.S)
        text = stand_in_answer(question.group(1) if question else "")
        for word in re.findall(r"\S+\s*", text):
            time.sleep(TOKEN_DELAY)
            yield word

    model_client.stream_chat = fake_stream
    rag.retrieve = lambda question, **kwargs: [
        {"source_document": "returns-policy", "section": "Returns Policy > Standard return window", "chunk_index": 1, "text": "Standard return window: 30 days from delivery.", "score": 0.9}
    ]

    import uvicorn

    from services.main import app

    uvicorn.run(app, host="127.0.0.1", port=int(os.getenv("PORT", "8000")), log_level="info")


if __name__ == "__main__":
    main()
